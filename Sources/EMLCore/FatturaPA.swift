import Foundation

/// An Italian FatturaPA / Fattura Elettronica XML found inside an email (including nested PEC).
public struct FatturaInvoice: Equatable {
    public let filename: String
    public let xmlData: Data

    public init(filename: String, xmlData: Data) {
        self.filename = filename
        self.xmlData = xmlData
    }
}

public enum FatturaPA {

    /// Recursively walk the MIME tree (nested `message/rfc822` / `.eml` included) and
    /// return every part whose payload is a `FatturaElettronica` invoice XML.
    /// Skips PEC `daticert.xml` and SdI `FileMetadati` wrappers.
    public static func findInvoices(in message: Message) -> [FatturaInvoice] {
        var found: [FatturaInvoice] = []
        walk(message.root, into: &found)
        return found
    }

    public static func isFatturaElettronica(_ data: Data) -> Bool {
        guard let name = rootLocalName(of: data) else { return false }
        return name == "FatturaElettronica"
    }

    public static func suggestedPDFFilename(for invoice: FatturaInvoice) -> String {
        let meta = parseMeta(invoice.xmlData)
        var parts: [String] = []
        if let cedente = meta.cedente, !cedente.isEmpty {
            parts.append(sanitizeFilename(cedente))
        }
        if let numero = meta.numero, !numero.isEmpty {
            parts.append(sanitizeFilename(numero))
        }
        if let data = meta.data, !data.isEmpty {
            parts.append(data)
        }
        if parts.isEmpty {
            let base = (invoice.filename as NSString).deletingPathExtension
            parts.append(base.isEmpty ? "fattura" : base)
        }
        return parts.joined(separator: "_") + ".pdf"
    }


    private struct InvoiceLabels {
        let lang: ContentLanguage
        var htmlLang: String { lang.htmlLang }
        var titleInvoice: String { lang == .italian ? "Fattura elettronica" : "Electronic invoice" }
        var titlePrefix: String { lang == .italian ? "Fattura" : "Invoice" }
        var number: String { lang == .italian ? "N." : "No." }
        var date: String { lang == .italian ? "Data" : "Date" }
        var type: String { lang == .italian ? "Tipo" : "Type" }
        var reason: String { lang == .italian ? "Causale" : "Reason" }
        var seller: String { lang == .italian ? "Cedente / prestatore" : "Seller" }
        var buyer: String { lang == .italian ? "Cessionario / committente" : "Buyer" }
        var detail: String { lang == .italian ? "Dettaglio" : "Line items" }
        var description: String { lang == .italian ? "Descrizione" : "Description" }
        var qty: String { lang == .italian ? "Q.tà" : "Qty" }
        var price: String { lang == .italian ? "Prezzo" : "Price" }
        var total: String { lang == .italian ? "Totale" : "Total" }
        var vat: String { "IVA" }
        var vatSummary: String { lang == .italian ? "Riepilogo IVA" : "VAT summary" }
        var rate: String { lang == .italian ? "Aliquota" : "Rate" }
        var taxable: String { lang == .italian ? "Imponibile" : "Taxable" }
        var tax: String { lang == .italian ? "Imposta" : "Tax" }
        var docTotal: String { lang == .italian ? "Totale documento" : "Document total" }
        var payment: String { lang == .italian ? "Pagamento" : "Payment" }
        var conditions: String { lang == .italian ? "Condizioni" : "Terms" }
        var method: String { lang == .italian ? "Modalità" : "Method" }
        var due: String { lang == .italian ? "Scadenza" : "Due" }
        var amount: String { lang == .italian ? "Importo" : "Amount" }
        var foot: String {
            lang == .italian
                ? "Generato da ZenaEML Viewer to PDF · FatturaPA XML → PDF"
                : "Generated by ZenaEML Viewer to PDF · FatturaPA XML → PDF"
        }
        var vatId: String { lang == .italian ? "P.IVA" : "VAT" }
        var taxCode: String { lang == .italian ? "C.F." : "Tax code" }
    }

    /// Human-readable HTML suitable for print / PDF.
    public static func htmlDocument(xmlData: Data, language: ContentLanguage = .systemPreferred) throws -> String {
        guard let doc = try? XMLDocument(data: xmlData, options: [.nodeLoadExternalEntitiesNever]) else {
            throw FatturaError.invalidXML
        }
        guard let root = doc.rootElement(), localName(root) == "FatturaElettronica" else {
            throw FatturaError.notAnInvoice
        }

        let header = firstChild(root, localName: "FatturaElettronicaHeader")
        let body = firstChild(root, localName: "FatturaElettronicaBody")
        let cedente = firstChild(header, localName: "CedentePrestatore")
        let cessionario = firstChild(header, localName: "CessionarioCommittente")
        let datiGen = firstChild(firstChild(body, localName: "DatiGenerali"), localName: "DatiGeneraliDocumento")
        let linee = children(firstChild(body, localName: "DatiBeniServizi"), localName: "DettaglioLinee")
        let riepiloghi = children(firstChild(body, localName: "DatiBeniServizi"), localName: "DatiRiepilogo")
        let pagamento = firstChild(body, localName: "DatiPagamento")

        let numero = text(datiGen, "Numero")
        let data = text(datiGen, "Data")
        let divisa = text(datiGen, "Divisa").isEmpty ? "EUR" : text(datiGen, "Divisa")
        let causale = text(datiGen, "Causale")
        let tipo = text(datiGen, "TipoDocumento")
        let L = InvoiceLabels(lang: language)

        var lineRows = ""
        for line in linee {
            lineRows += """
            <tr>
              <td>\(escape(text(line, "NumeroLinea")))</td>
              <td>\(escape(text(line, "Descrizione")))</td>
              <td class="num">\(escape(text(line, "Quantita")))</td>
              <td class="num">\(escape(text(line, "PrezzoUnitario")))</td>
              <td class="num">\(escape(text(line, "PrezzoTotale")))</td>
              <td class="num">\(escape(text(line, "AliquotaIVA")))%</td>
            </tr>
            """
        }

        var riepilogoRows = ""
        var imponibileTot = 0.0
        var impostaTot = 0.0
        for r in riepiloghi {
            let imp = Double(text(r, "ImponibileImporto").replacingOccurrences(of: ",", with: ".")) ?? 0
            let iva = Double(text(r, "Imposta").replacingOccurrences(of: ",", with: ".")) ?? 0
            imponibileTot += imp
            impostaTot += iva
            riepilogoRows += """
            <tr>
              <td class="num">\(escape(text(r, "AliquotaIVA")))%</td>
              <td class="num">\(escape(text(r, "ImponibileImporto")))</td>
              <td class="num">\(escape(text(r, "Imposta")))</td>
            </tr>
            """
        }
        let totale = String(format: "%.2f", imponibileTot + impostaTot)

        var pagamentoHTML = ""
        if let pagamento {
            let det = firstChild(pagamento, localName: "DettaglioPagamento")
            pagamentoHTML = """
            <h2>\(L.payment)</h2>
            <p>
              \(L.conditions): \(escape(text(pagamento, "CondizioniPagamento"))) ·
              \(L.method): \(escape(text(det, "ModalitaPagamento"))) ·
              \(L.due): \(escape(text(det, "DataScadenzaPagamento"))) ·
              \(L.amount): \(escape(text(det, "ImportoPagamento"))) \(escape(divisa))
              \(text(det, "IBAN").isEmpty ? "" : "· IBAN: \(escape(text(det, "IBAN")))")
            </p>
            """
        }

        return """
        <!DOCTYPE html>
        <html lang="\(L.htmlLang)">
        <head>
          <meta charset="utf-8">
          <title>\(L.titlePrefix) \(escape(numero))</title>
          <style>
            body { font-family: -apple-system, Helvetica, Arial, sans-serif; color: #1a1a1a; margin: 36px; font-size: 12px; }
            h1 { font-size: 22px; margin: 0 0 4px; }
            h2 { font-size: 14px; margin: 22px 0 8px; border-bottom: 1px solid #ddd; padding-bottom: 4px; }
            .meta { color: #555; margin-bottom: 18px; }
            .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 18px; margin: 16px 0 8px; }
            .box { background: #f7f7f8; padding: 12px 14px; border-radius: 8px; }
            .box strong { display: block; margin-bottom: 6px; }
            table { width: 100%; border-collapse: collapse; margin-top: 8px; }
            th, td { border-bottom: 1px solid #e5e5e5; padding: 7px 6px; text-align: left; vertical-align: top; }
            th { font-size: 11px; text-transform: uppercase; letter-spacing: 0.03em; color: #666; }
            td.num, th.num { text-align: right; font-variant-numeric: tabular-nums; }
            .totals { margin-top: 16px; width: 280px; margin-left: auto; }
            .totals td { border: none; padding: 4px 6px; }
            .totals tr.grand td { font-weight: 700; font-size: 14px; border-top: 2px solid #222; padding-top: 8px; }
            .foot { margin-top: 28px; color: #888; font-size: 10px; }
          </style>
        </head>
        <body>
          <h1>\(L.titleInvoice)</h1>
          <div class="meta">
            \(L.number) \(escape(numero)) · \(L.date) \(escape(data)) · \(escape(divisa))
            \(tipo.isEmpty ? "" : "· \(L.type) \(escape(tipo))")
            \(causale.isEmpty ? "" : "<br>\(L.reason): \(escape(causale))")
          </div>
          <div class="grid">
            <div class="box">
              <strong>\(L.seller)</strong>
              \(partyHTML(cedente, language: language))
            </div>
            <div class="box">
              <strong>\(L.buyer)</strong>
              \(partyHTML(cessionario, language: language))
            </div>
          </div>
          <h2>\(L.detail)</h2>
          <table>
            <thead>
              <tr>
                <th>#</th><th>\(L.description)</th>
                <th class="num">\(L.qty)</th><th class="num">\(L.price)</th>
                <th class="num">\(L.total)</th><th class="num">\(L.vat)</th>
              </tr>
            </thead>
            <tbody>
              \(lineRows)
            </tbody>
          </table>
          <h2>\(L.vatSummary)</h2>
          <table>
            <thead><tr><th class="num">\(L.rate)</th><th class="num">\(L.taxable)</th><th class="num">\(L.tax)</th></tr></thead>
            <tbody>\(riepilogoRows)</tbody>
          </table>
          <table class="totals">
            <tr><td>\(L.taxable)</td><td class="num">\(String(format: "%.2f", imponibileTot)) \(escape(divisa))</td></tr>
            <tr><td>\(L.vat)</td><td class="num">\(String(format: "%.2f", impostaTot)) \(escape(divisa))</td></tr>
            <tr class="grand"><td>\(L.docTotal)</td><td class="num">\(totale) \(escape(divisa))</td></tr>
          </table>
          \(pagamentoHTML)
          <p class="foot">\(L.foot)</p>
        </body>
        </html>
        """
    }

    // MARK: - Walk / detect

    private static func walk(_ part: Part, into: inout [FatturaInvoice]) {
        if !part.isMultipart {
            let data = part.decodedBody()
            if isFatturaElettronica(data) {
                let name = part.filename ?? "fattura.xml"
                into.append(FatturaInvoice(filename: name, xmlData: data))
            }
        }
        for sub in part.parts {
            walk(sub, into: &into)
        }
    }

    private static func rootLocalName(of data: Data) -> String? {
        guard let doc = try? XMLDocument(data: data, options: [.nodeLoadExternalEntitiesNever]),
              let root = doc.rootElement() else { return nil }
        return localName(root)
    }

    private static func localName(_ node: XMLNode) -> String {
        if let el = node as? XMLElement, let local = el.localName, !local.isEmpty {
            return local
        }
        let name = node.name ?? ""
        if let idx = name.lastIndex(of: ":") {
            return String(name[name.index(after: idx)...])
        }
        return name
    }

    // MARK: - XML helpers

    private static func firstChild(_ parent: XMLElement?, localName name: String) -> XMLElement? {
        guard let parent else { return nil }
        return parent.children?.compactMap { $0 as? XMLElement }.first { localName($0) == name }
    }

    private static func children(_ parent: XMLElement?, localName name: String) -> [XMLElement] {
        guard let parent else { return [] }
        return parent.children?.compactMap { $0 as? XMLElement }.filter { localName($0) == name } ?? []
    }

    private static func text(_ parent: XMLElement?, _ name: String) -> String {
        firstChild(parent, localName: name)?.stringValue?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
    }

    private static func partyHTML(_ party: XMLElement?, language: ContentLanguage) -> String {
        let anag = firstChild(firstChild(party, localName: "DatiAnagrafici"), localName: "Anagrafica")
        let idFisc = firstChild(firstChild(party, localName: "DatiAnagrafici"), localName: "IdFiscaleIVA")
        let sede = firstChild(party, localName: "Sede")
        let denom = text(anag, "Denominazione")
        let cf = text(firstChild(party, localName: "DatiAnagrafici"), "CodiceFiscale")
        let piva = text(idFisc, "IdCodice")
        let indirizzo = [text(sede, "Indirizzo"), text(sede, "CAP"), text(sede, "Comune"), text(sede, "Provincia")]
            .filter { !$0.isEmpty }.joined(separator: ", ")
        var lines = "<div>\(escape(denom))</div>"
        let L = InvoiceLabels(lang: language)
        if !piva.isEmpty { lines += "<div>\(L.vatId) \(escape(text(idFisc, "IdPaese")))\(escape(piva))</div>" }
        if !cf.isEmpty { lines += "<div>\(L.taxCode) \(escape(cf))</div>" }
        if !indirizzo.isEmpty { lines += "<div>\(escape(indirizzo))</div>" }
        return lines
    }

    private static func escape(_ s: String) -> String {
        s.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
    }

    private static func sanitizeFilename(_ s: String) -> String {
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "-_"))
        let mapped = s.unicodeScalars.map { allowed.contains($0) ? Character($0) : Character("_") }
        let collapsed = String(mapped)
            .replacingOccurrences(of: "_+", with: "_", options: .regularExpression)
            .trimmingCharacters(in: CharacterSet(charactersIn: "_"))
        return String(collapsed.prefix(48))
    }

    private struct Meta {
        var cedente: String?
        var numero: String?
        var data: String?
    }

    private static func parseMeta(_ data: Data) -> Meta {
        guard let doc = try? XMLDocument(data: data, options: [.nodeLoadExternalEntitiesNever]),
              let root = doc.rootElement() else { return Meta() }
        let header = firstChild(root, localName: "FatturaElettronicaHeader")
        let body = firstChild(root, localName: "FatturaElettronicaBody")
        let cedente = firstChild(header, localName: "CedentePrestatore")
        let anag = firstChild(firstChild(cedente, localName: "DatiAnagrafici"), localName: "Anagrafica")
        let datiGen = firstChild(firstChild(body, localName: "DatiGenerali"), localName: "DatiGeneraliDocumento")
        return Meta(
            cedente: text(anag, "Denominazione"),
            numero: text(datiGen, "Numero"),
            data: text(datiGen, "Data")
        )
    }
}

public enum FatturaError: Error, LocalizedError {
    case invalidXML
    case notAnInvoice
    case pdfFailed(String)

    public var errorDescription: String? {
        switch self {
        case .invalidXML: return "Invalid invoice XML"
        case .notAnInvoice: return "Not a FatturaElettronica document"
        case .pdfFailed(let s): return s
        }
    }
}
